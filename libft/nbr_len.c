#include "libft.h"

int	nbr_len(int n)
{
	int		i;
	long	j;

	j = n;
	i = 0;
	if (j < 0)
	{
		j = -j;
		i++;
	}
	while (j > 0)
	{
		j = j / 10;
		i++;
	}
	return (i);
}
